export const BCP47_MAP = Object.fromEntries(
  DEFAULT_VOICE_LANGUAGES.map((l) => [l.code, l.bcp47])
);

export function findLanguageEntry(languages, codeOrName) {
  if (!codeOrName) return languages[0];
  const low = String(codeOrName).trim().toLowerCase();
  return (
    languages.find(
      (l) =>
        l.code.toLowerCase() === low ||
        l.name.toLowerCase() === low ||
        l.bcp47?.toLowerCase() === low ||
        low.startsWith(`${l.code.toLowerCase()}-`) ||
        low.startsWith(`${l.code.toLowerCase()}_`) ||
        l.name.toLowerCase().startsWith(low)
    ) || languages[0]
  );
}
